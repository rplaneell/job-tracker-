"""Check the company boards that harvest.py found, and keep the ones with roles in the owner's regions.

Every request goes through the client given in, which in real use is the robots aware PoliteClient.
"""
from __future__ import annotations

import json
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

import httpx
import yaml

from jobtracker.models import Role
from jobtracker.registry import Source

Fetch = Callable[[httpx.Client, Source], list[Role]]

BASIS = "official public feed or API; board found in the Common Crawl web archive"


@dataclass(frozen=True)
class BoardCheck:
    kind: str
    board: str
    total: int
    in_regions: int
    city: str


def display_name(board: str) -> str:
    bare = board[3:] if board.startswith("eu:") else board
    return " ".join(word.capitalize() for word in bare.replace("_", "-").split("-") if word)


def check_board(client, kind: str, board: str, countries: list[str], adapters: dict[str, Fetch]) -> BoardCheck | None:
    """Read one board. None means it could not be read (missing, blocked by robots, or odd)."""
    source = Source(display_name(board), kind, board, "", "")
    try:
        roles = adapters[kind](client, source)
    except Exception:  # a broken board is skipped, never fatal
        return None
    here = [r for r in roles if r.country in countries]
    cities = Counter(r.city for r in here if r.city)
    return BoardCheck(kind, board, len(roles), len(here), cities.most_common(1)[0][0] if cities else "")


def load_state(path: Path) -> dict:
    try:
        return json.loads(Path(path).read_text())
    except (OSError, ValueError):
        return {}


def save_state(path: Path, state: dict) -> None:
    Path(path).write_text(json.dumps(state, indent=0, sort_keys=True))


def verify_candidates(
    candidates: dict[tuple[str, str], str],
    client,
    countries: list[str],
    state: dict,
    limit: int | None = None,
    adapters: dict[str, Fetch] | None = None,
) -> list[BoardCheck]:
    """Check boards not seen before. Every outcome is written to state so a rerun skips it."""
    if adapters is None:
        from jobtracker.run import ADAPTERS

        adapters = ADAPTERS
    kept: list[BoardCheck] = []
    done = 0
    for (kind, _lower), board in sorted(candidates.items()):
        key = f"{kind}:{board.lower()}"
        if key in state:
            continue
        if limit is not None and done >= limit:
            break
        done += 1
        check = check_board(client, kind, board, countries, adapters)
        if check is None:
            state[key] = {"error": "could not be read", "kind": kind, "board": board}
            continue
        state[key] = {
            "kind": kind, "board": board, "total": check.total, "in_regions": check.in_regions, "city": check.city,
        }
        if check.in_regions >= 1:
            kept.append(check)
    return kept


def checks_from_state(state: dict) -> list[BoardCheck]:
    """Every board that has ever passed, so a rerun adds to the list instead of starting over."""
    return [
        BoardCheck(v["kind"], v["board"], v["total"], v["in_regions"], v.get("city", ""))
        for v in state.values()
        if v.get("in_regions", 0) >= 1 and "board" in v
    ]


def write_generated(path: Path, checks: list[BoardCheck]) -> None:
    entries = [
        {
            "name": display_name(c.board),
            "kind": c.kind,
            "board": c.board,
            "city": c.city,
            "field": "",
            "terms": "ok",
            "basis": BASIS,
        }
        for c in sorted(checks, key=lambda c: (-c.in_regions, c.kind, c.board))
    ]
    header = "# Generated by the board finder. Do not edit by hand: re-run it instead.\n"
    Path(path).write_text(header + yaml.safe_dump(entries, sort_keys=False, allow_unicode=True))
